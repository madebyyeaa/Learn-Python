a: int = 1;
b: int = 2;

# operator perbandingan
print(a > b);  # membandingkan apakah nilai a lebih besar dari b  
print(a < b);  # membandingkan apakah nilai a lebih kecil dari b  
print(a >= b); # membandingkan apakah nilai a lebih besar atau sama dengan b
print(a <= b); # membandingkan apakah nilai a lebih kecil atau sama dengan b
print(a == b); # membandingkan apakah nilai a dan b sama 
print(a != b); # membandingkan apakah nilai a dan b tidak sama


